def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--quality", type=Path, required=True)
    ap.add_argument("--test-results", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--release", type=Path, help="reviewed relative report/ZIP locations for final integration")
    args = ap.parse_args()
    if args.out.exists():
        ap.error("staging output exists; use a fresh directory")
    n = E.validate_test_record(E.load(args.test_results), ROOT)
    q = E.load(args.quality)
    for rel, expected in q["provenance"]["files"].items():
        if E.sha(ROOT / rel) != expected:
            raise ValueError("statistics source changed: " + rel)
    for rel, text in render_documents(ROOT, q, n, E.load(args.release) if args.release else None).items():
        path = args.out / rel; path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
