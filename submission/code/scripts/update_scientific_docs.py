def replace_section(text, start, end, replacement):
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError("ambiguous document section")
    a, b = text.index(start), text.index(end)
    if b <= a:
        raise ValueError("reversed document sections")
    return text[:a] + replacement.rstrip() + "\n\n" + text[b:]


def science_block(c, tests_run):
    facts = E.claims(c)
    return ("<!-- generated by scripts/update_scientific_docs.py; edit the generator -->\n"
            + E.quality_markdown(c["quality"]).replace("# 泛化数据质量分层（从原始记录和已保存模型重算）", "### 泛化分层")
            + "\n### 积分步数与模型身份\n\n" + facts["efficiency"]
            + "\n\n正式模型为 v1；研究中保留的改进模型为 v2，主动学习 v3 未采用。"
            + "\n\n### 条带选择的证据范围\n\n" + facts["bands"]
            + "\n\n### 固定参数下的最佳匹配\n\n" + facts["inverse"]
            + f"\n\n本轮实际执行 **{tests_run} 项单元测试**并通过；数量来自执行记录并绑定当前源码。"
            + "历史 89、95、99 项属于不同版本，不代表当前测试数。\n"
            + "历史多种子与旧运行耗时没有在本轮重新计算；有限谱数值检查不是全谱数学证明。\n"
            + "<!-- end generated scientific evidence -->\n")


def inversion_markdown(c):
    inv, b = c["inversion"], c["best_match"]
    e, given = inv["estimate"], inv["given_spots"]
    maximum = max(b["stability"]["decision"]["sampled_maxima"])
    return ("## 2. 任务 3 反演与最佳匹配\n\n"
            f"只反演 F、k：**F={e['F']:.7f}，k={e['k']:.7f}**，相对题给参考值的误差 "
            f"{e['F']/given['F']-1:+.2%} / {e['k']/given['k']-1:+.2%}。\n\n"
            f"启发式目标函数容差带：F∈{e['band_F']}，k∈{e['band_k']}；不是覆盖率校准的置信区间。\n\n"
            + E.claims(c)["inverse"]
            + f"\n\n最佳匹配 MAT 的保存证书完整残差 {b['mat_certificate']['residual']['value']:.3e}；"
            f"历史三组配置摘要最大实部 {maximum:+.3e}。原摘要未保存逐特征对残差与向量；补充证据独立保留，不改写原记录。\n\n"
            "目标、原代表解与最佳匹配均保留，参数未因多初值搜索改变。复现搜索成本较高；本轮仅重算统计并核对保存证据。\n")


def portable_verification_markdown():
    """Public wording follows the actual portable acceptance protocol."""
    return (
        "`verify` 的每项输出带 `verification_mode`：优先严格验收；仅算子指纹不同或残差对账超出严格比较预算时，尝试 `portable`。\n"
        "即使 L/M 指纹一致，残差归约的浮点舍入差异也可进入 portable；模式不按 x86/ARM 名称选择。\n"
        "portable 保留完整的证书结构、参数、种子、公式、容差与 MAT 哈希检查。网格哈希、点面数和 robust 算子类型须一致，"
        "总质量在相对 1e-12 内一致；保存值与本机完整残差均须满足原有 ≤ 1e-11 标准，且二者在固定 1e-12 绝对比较预算内一致。\n"
        "这是跨平台数值验收，不是完整 L/M 矩阵逐元素等价证明。\n")


def validate_release_note(note):
    if not isinstance(note, str) or "???" in note or "\ufffd" in note:
        raise ValueError("release report note contains corrupted text")
    return note

